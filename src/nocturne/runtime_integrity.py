"""Exact environment integrity and already-issued frozen inference replay.

Checksums detect drift, not a malicious operator able to rewrite trusted metadata.
This module never fits models, issues forecasts or changes historical evidence.
"""
import base64
import hashlib
import importlib.metadata as metadata
from pathlib import Path
import re


def check_capture_window(now, scheduled_times, budget_seconds):
    from datetime import datetime
    if now.tzinfo is None or not 1 <= budget_seconds <= 120:
        raise ValueError('invalid capture admission clock/budget')
    if scheduled_times and budget_seconds > 30:
        raise ValueError('live scheduled host captures must fit the 30-second maintenance budget')
    for stamp in scheduled_times:
        deadline = datetime.fromisoformat(stamp.replace('Z', '+00:00'))
        if deadline.tzinfo is None:
            raise ValueError('scheduled deadline lacks timezone')
        if 0 <= (deadline - now).total_seconds() <= budget_seconds + 15:
            raise BlockingIOError('scheduled tick imminent; defer backup rather than block forecast work')
    return {'status': 'CAPTURE_WINDOW_CHECKED', 'scheduled_deadlines': scheduled_times,
            'budget_seconds': budget_seconds, 'margin_seconds': 15}


def normalized_name(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def exact_pins(paths):
    pins = {}
    for path in paths:
        for line in Path(path).read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+!-]+)", line)
            if not match:
                raise ValueError("only exact unmarked package pins are supported")
            name, version = match.groups()
            name = normalized_name(name)
            if name in pins:
                raise ValueError("duplicate dependency pin")
            pins[name] = version
    if not pins:
        raise ValueError("empty dependency lock")
    return pins


def file_hash(path):
    checksum = hashlib.sha256()
    with Path(path).open("rb") as handle:
        while chunk := handle.read(65536):
            checksum.update(chunk)
    return checksum.hexdigest()


def verify_wheelhouse(root, manifest, pins):
    root = Path(root).resolve()
    if manifest["target"] != "windows-x86_64-cpython-314":
        raise ValueError("unsupported dependency lock target")
    seen, names = set(), set()
    total = 0
    for entry in manifest["wheels"]:
        filename = entry["filename"]
        name = normalized_name(entry["name"])
        if (Path(filename).name != filename or "\\" in filename or ":" in filename or not filename.endswith(".whl")
                or name in names or filename in seen or pins.get(name) != entry["version"]):
            raise ValueError("unsafe, duplicate or unpinned wheel")
        path = root / filename
        if path.is_symlink() or not path.is_file() or path.stat().st_size != entry["bytes"] or file_hash(path) != entry["sha256"]:
            raise ValueError("dependency wheel integrity mismatch")
        if entry["sha256"] != entry["pypi_sha256"]:
            raise ValueError("wheel differs from recorded upstream digest")
        seen.add(filename)
        names.add(name)
        total += path.stat().st_size
    if names != set(pins) or {p.name for p in root.iterdir()} != seen:
        raise ValueError("wheelhouse is incomplete or contains unexpected files")
    return {"status": "VERIFIED_WHEEL_BYTES", "wheels": len(seen), "bytes": total}


def verify_installed(pins, prefix):
    """Audit installed RECORD hashes inside the venv; never print file contents."""
    prefix = Path(prefix).resolve()
    packages, checked = [], 0
    for name, expected in sorted(pins.items()):
        distribution = metadata.distribution(name)
        if distribution.version != expected:
            raise ValueError(f"dependency version mismatch: {name}")
        files = distribution.files
        if not files:
            raise ValueError(f"installed RECORD absent: {name}")
        count = 0
        for item in files:
            path = Path(distribution.locate_file(item)).resolve()
            if not path.is_relative_to(prefix):
                raise ValueError(f"dependency outside isolated prefix: {name}")
            if item.hash is None:
                continue  # RECORD and generated bytecode have no declared hash.
            if item.hash.mode != "sha256" or not path.is_file():
                raise ValueError(f"unsupported or missing installed file: {name}")
            actual = base64.urlsafe_b64encode(bytes.fromhex(file_hash(path))).decode().rstrip("=")
            if actual != item.hash.value or (item.size is not None and path.stat().st_size != item.size):
                raise ValueError(f"installed dependency RECORD mismatch: {name}")
            count += 1
        if not count:
            raise ValueError(f"no hashed installed files: {name}")
        checked += count
        packages.append({"name": name, "version": expected, "hashed_files": count})
    return {"status": "VERIFIED_INSTALLED_RECORDS", "files": checked, "packages": packages,
            "limitations": "Trusted local RECORD metadata; unhashed RECORD/bytecode excluded. Not malware scanning or protection against coordinated metadata tampering."}


def verify_frozen_inference(artifact, forecasts):
    from .adapters.snapshots import canonical, digest
    from .shadow.features import FeatureSnapshot, feature_matrix
    import numpy as np
    results = []
    seen = set()
    for forecast in forecasts:
        if forecast["forecast_id"] in seen or forecast["model_id"] != artifact.model_id or forecast["model_version"] != artifact.version:
            raise ValueError("inference replay identity mismatch")
        seen.add(forecast["forecast_id"])
        snapshot = FeatureSnapshot(asof=forecast.get("feature_asof", forecast["created_at"]),
                                   data_date=forecast["data_date"], reference_close=forecast["reference_close"],
                                   values=forecast["features"], rows_used=forecast["rows_used"],
                                   dataset_sha256=forecast["dataset_sha256"])
        revision = forecast.get("inference_revision", "legacy-unadjusted")
        if revision == "residual-adjusted-v1":
            actual = artifact.predict(snapshot)
        elif revision == "legacy-unadjusted":
            matrix = feature_matrix(snapshot)[list(artifact.features)]
            raw = [float(artifact.models[q].predict(matrix)[0]) for q in ("p50", "p80", "p90")]
            actual = dict(zip(("p50", "p80", "p90"), map(float, np.sort(np.maximum(raw, 0.0)))))
        else:
            raise ValueError("unsupported frozen inference cohort")
        expected = forecast["quantiles"]
        if set(expected) != set(actual) or any(float(actual[k]).hex() != float(expected[k]).hex() for k in actual):
            raise ValueError("frozen inference differs from issued quantiles")
        results.append({"forecast_id": forecast["forecast_id"], "forecast_sha256": digest(canonical(forecast)),
                        "inference_revision": revision, "quantiles": actual, "comparison": "EXACT_FLOAT_HEX"})
    if not results:
        raise ValueError("no immutable inference replay cases")
    return {"status": "VERIFIED_FROZEN_INFERENCE", "model_id": artifact.model_id, "model_version": artifact.version,
            "artifact_digests": artifact.metadata["artifact_digests"], "records": results,
            "limits": "Replay of stored feature rows, not upstream feature reconstruction or predictive validation. Run original archived-source proof gates separately."}
